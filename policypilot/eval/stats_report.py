"""Writes docs/EVAL_STATS.md: every saved evaluation result with its 95% confidence interval.

It reads the results files the evaluations saved (no AI calls) and re-runs only the retrieval step,
which is cheap and deterministic. So the intervals can be refreshed at any time without spending
API credits, and docs/EVAL_RESULTS.md (which has hand-written analysis) is never touched.
"""

from __future__ import annotations

import json
from datetime import date

from ..config import PROJECT_ROOT, Settings
from ..retrieval import PolicyIndex
from .run_eval import SUITES, eval_retrieval, is_provisional, load_labels
from .stats import N_BOOT, SEED, compare, e2e_intervals, mean_intervals

E2E_ROWS = [("Precision", "precision"), ("Recall", "recall"), ("Impact accuracy", "impact_accuracy"),
            ("Abstention", "abstention"), ("Fully correct requirements", "fully_correct")]
METHOD_NAMES = {"bm25": "Keywords (BM25)", "dense": "Meaning (embeddings)", "hybrid": "Hybrid",
                "hybrid+rerank": "Hybrid + rerank"}


def _ci(m: dict) -> str:
    if m["value"] is None:
        return "—"
    return f"{100 * m['value']:.0f}% [{100 * m['low']:.0f}–{100 * m['high']:.0f}]"


def _run_name(run: dict, runs: list[dict]) -> str:
    if run["mode"] == "offline":
        return "No-AI baseline"
    agents = [r for r in runs if r["mode"] != "offline"]
    name = f"AI agent · {run['model']}"
    return name if len(agents) == 1 else f"{name} · run {agents.index(run) + 1}"


def suite_section(settings: Settings, index: PolicyIndex, suite: str) -> list[str]:
    path = settings.data_dir / "eval" / SUITES[suite][2]
    if not path.exists():
        return []
    saved = json.loads(path.read_text(encoding="utf-8"))
    labels = load_labels(settings, suite)
    lines = [f"## `{suite}` suite", ""]
    if is_provisional(labels):
        lines += ["> **Provisional:** some labels are unreviewed drafts.", ""]

    retrieval = eval_retrieval(index, settings, suite=suite)
    n = len(next(iter(retrieval.values()))["per_query"])
    lines += [f"**Retrieval** ({n} requirements):", "",
              "| Method | Recall@1 | Recall@3 | Recall@5 | MRR |", "|---|---|---|---|---|"]
    for method, r in retrieval.items():
        ci = mean_intervals(r["per_query"], ["recall@1", "recall@3", "recall@5", "rr"])
        lines.append(f"| {METHOD_NAMES[method]} | " + " | ".join(_ci(ci[k]) for k in ("recall@1", "recall@3", "recall@5"))
                     + f" | {ci['rr']['value']:.2f} [{ci['rr']['low']:.2f}–{ci['rr']['high']:.2f}] |")

    runs = saved.get("end_to_end", [])
    if runs:
        intervals = [e2e_intervals(r["details"]) for r in runs]
        names = [_run_name(r, runs) for r in runs]
        lines += ["", f"**End to end** ({len(runs[0]['details'])} requirements):", "",
                  "| Metric | " + " | ".join(names) + " |", "|---|" + "---|" * len(runs)]
        for title, key in E2E_ROWS:
            if all(iv[key]["value"] is None for iv in intervals):
                continue
            lines.append(f"| {title} | " + " | ".join(_ci(iv[key]) for iv in intervals) + " |")
        baseline = next((r for r in runs if r["mode"] == "offline"), None)
        for run in runs:
            if run is baseline or baseline is None:
                continue
            c = compare(run["details"], baseline["details"])
            verdict = "significant at α = 0.05" if c["p_value"] < 0.05 else "not significant at α = 0.05"
            lines += ["", f"**{_run_name(run, runs)} vs. baseline** (exact McNemar test on fully correct "
                      f"requirements, {c['pairs']} pairs): only the agent right on {c['only_first']}, only the "
                      f"baseline right on {c['only_second']}, both on {c['both']}, neither on {c['neither']}. "
                      f"p = {c['p_value']:.4f}, {verdict}."]
    else:
        lines += ["", "_No end-to-end run saved for this suite yet._"]
    return lines + [""]


def write(settings: Settings) -> str:
    index = PolicyIndex.build(settings)
    lines = [
        "# Evaluation statistics",
        "",
        f"_Generated by `python -m policypilot stats` on {date.today().isoformat()} from the saved results "
        f"in `data/eval/`. Brackets show 95% confidence intervals: percentile bootstrap over requirements, "
        f"{N_BOOT:,} resamples, seed {SEED}. Method: [EVAL_PLAN.md](EVAL_PLAN.md)._",
        "",
        "**How to read this.** With a few dozen requirements, intervals are wide. A 96% that could be "
        "anywhere from 88% to 100% is the honest result. Two systems whose intervals overlap heavily "
        "may not really differ, which is what the McNemar test checks.",
        "",
    ]
    for suite in SUITES:
        lines += suite_section(settings, index, suite)
    md = "\n".join(lines)
    (PROJECT_ROOT / "docs" / "EVAL_STATS.md").write_text(md, encoding="utf-8")
    return md
